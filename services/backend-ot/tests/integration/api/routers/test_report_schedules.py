"""
Integration tests for report schedules (/api/reports/site/{site_id}/schedules and the dispatcher).

Guards schedules against a real database: CRUD with the next time worked out on the site's clock
(none while disabled), templates of other sites refused, a deleted template taking its schedules
with it; and dispatching: a due schedule queues its template's report for the occurrence's window,
moves to its next time once (after downtime, a single catch-up), never twice for one occurrence,
prunes only its own reports (keep_last, keep_days), records a failed report when the template no
longer fits the site, and its report is then generated by the worker like any other.
"""

from datetime import UTC, datetime, timedelta
from zoneinfo import ZoneInfo

from httpx import AsyncClient
from pydantic import TypeAdapter

from integration.factories import create_device, create_site, point_request, upsert_points
from reports.backend_ot_source import BackendOtReportSource
from reports.scheduling import dispatch_due_schedules
from reports.worker import process_queued_runs
from schemas.reports import CalendarWindow, ReportDefinition, RollingWindow, TextBlock
from schemas.reports.api import (
    ReportRunCreateRequest,
    ReportRunResponse,
    ReportRunSummary,
    ReportScheduleResponse,
    ReportTemplateCreateRequest,
    ReportTemplateResponse,
)
from schemas.reports.schedules import (
    DailyCadence,
    ReportScheduleCreateRequest,
    ReportScheduleUpdateRequest,
)

SCHEDULE_LIST = TypeAdapter(list[ReportScheduleResponse])
RUN_LIST = TypeAdapter(list[ReportRunSummary])
DAILY_6 = DailyCadence(kind="daily", time="06:00")
YESTERDAY = CalendarWindow(kind="calendar", period="day", offset=-1)


def url(site_id: int, path: str = "") -> str:
    return f"/api/reports/site/{site_id}{path}"


async def site_with_template(client: AsyncClient, **site_overrides: object) -> tuple[int, ReportTemplateResponse]:
    site = await create_site(client, **site_overrides)
    definition = ReportDefinition(window=YESTERDAY, blocks=[TextBlock(kind="text", id="intro", body="{site_name}, {window_start}")])
    response = await client.post(url(site.site_id, "/templates"), json=ReportTemplateCreateRequest(name="Daily", definition=definition).model_dump(mode="json"))
    assert response.status_code == 201, response.text
    return site.site_id, ReportTemplateResponse.model_validate(response.json())


async def create_schedule(client: AsyncClient, site_id: int, **fields: object) -> ReportScheduleResponse:
    body = ReportScheduleCreateRequest.model_validate({"cadence": DAILY_6.model_dump(), **fields})
    response = await client.post(url(site_id, "/schedules"), json=body.model_dump(mode="json"))
    assert response.status_code == 201, response.text
    return ReportScheduleResponse.model_validate(response.json())


async def make_due(db, schedule_id: int, due_at: datetime) -> None:
    await db.execute("UPDATE report_schedules SET next_run_at = $1 WHERE id = $2", due_at, schedule_id)


async def runs_of(client: AsyncClient, site_id: int) -> list[ReportRunSummary]:
    return RUN_LIST.validate_python((await client.get(url(site_id, "/runs"))).json())


class TestScheduleCrud:
    async def test_create_works_out_the_next_time_on_the_site_clock(self, client):
        site_id, template = await site_with_template(client, timezone="America/Los_Angeles")
        schedule = await create_schedule(client, site_id, template_id=template.id, keep_last=7)
        assert (schedule.template_name, schedule.timezone, schedule.enabled, schedule.keep_last) == ("Daily", "America/Los_Angeles", True, 7)
        assert schedule.next_run_at is not None and schedule.next_run_at > datetime.now(UTC)
        local = schedule.next_run_at.astimezone(ZoneInfo("America/Los_Angeles"))
        assert (local.hour, local.minute) == (6, 0)

        listed = SCHEDULE_LIST.validate_python((await client.get(url(site_id, "/schedules"))).json())
        assert [entry.id for entry in listed] == [schedule.id]
        fetched = await client.get(url(site_id, f"/schedules/{schedule.id}"))
        assert ReportScheduleResponse.model_validate(fetched.json()) == schedule

    async def test_disabled_has_no_next_time_until_enabled(self, client):
        site_id, template = await site_with_template(client)
        schedule = await create_schedule(client, site_id, template_id=template.id, enabled=False)
        assert schedule.next_run_at is None
        body = ReportScheduleUpdateRequest(enabled=True).model_dump(mode="json", exclude_unset=True)
        enabled = ReportScheduleResponse.model_validate((await client.put(url(site_id, f"/schedules/{schedule.id}"), json=body)).json())
        assert enabled.enabled and enabled.next_run_at is not None

    async def test_update_changes_cadence_and_clears_retention(self, client):
        site_id, template = await site_with_template(client)
        schedule = await create_schedule(client, site_id, template_id=template.id, keep_last=3, keep_days=30)
        body = {"cadence": {"kind": "weekly", "time": "07:30", "weekdays": [0]}, "keep_last": None}
        response = await client.put(url(site_id, f"/schedules/{schedule.id}"), json=body)
        assert response.status_code == 200, response.text
        updated = ReportScheduleResponse.model_validate(response.json())
        assert (updated.cadence.kind, updated.keep_last, updated.keep_days) == ("weekly", None, 30)
        assert updated.next_run_at is not None and updated.next_run_at.weekday() == 0

    async def test_template_of_another_site_is_400(self, client):
        site_id, _ = await site_with_template(client)
        _, other_template = await site_with_template(client, name="Other")
        body = ReportScheduleCreateRequest(template_id=other_template.id, cadence=DAILY_6)
        response = await client.post(url(site_id, "/schedules"), json=body.model_dump(mode="json"))
        assert response.status_code == 400

    async def test_bad_cadence_is_422(self, client):
        site_id, template = await site_with_template(client)
        response = await client.post(url(site_id, "/schedules"), json={"template_id": template.id, "cadence": {"kind": "daily", "time": "25:00"}})
        assert response.status_code == 422

    async def test_delete_keeps_its_reports_and_a_deleted_template_takes_its_schedules(self, client, db):
        site_id, template = await site_with_template(client)
        schedule = await create_schedule(client, site_id, template_id=template.id)
        await make_due(db, schedule.id, datetime.now(UTC) - timedelta(minutes=1))
        assert await dispatch_due_schedules(BackendOtReportSource()) == 1
        assert (await client.delete(url(site_id, f"/schedules/{schedule.id}"))).status_code == 200
        (run,) = await runs_of(client, site_id)
        assert run.schedule_id is None

        again = await create_schedule(client, site_id, template_id=template.id)
        assert (await client.delete(url(site_id, f"/templates/{template.id}"))).status_code == 200
        assert (await client.get(url(site_id, f"/schedules/{again.id}"))).status_code == 404

    async def test_unknown_schedule_is_404(self, client):
        site_id, _ = await site_with_template(client)
        assert (await client.get(url(site_id, "/schedules/4242"))).status_code == 404
        assert (await client.delete(url(site_id, "/schedules/4242"))).status_code == 404


class TestDispatch:
    async def test_due_schedule_queues_the_report_for_its_occurrence(self, client, db):
        site_id, template = await site_with_template(client)
        schedule = await create_schedule(client, site_id, template_id=template.id)
        due_at = datetime(2026, 10, 14, 6, 0, tzinfo=UTC)  # a UTC site: yesterday is Oct 13
        await make_due(db, schedule.id, due_at)

        now = due_at + timedelta(minutes=3)  # the dispatcher ran a little late
        assert await dispatch_due_schedules(BackendOtReportSource(), clock=lambda: now) == 1
        (run,) = await runs_of(client, site_id)
        assert (run.status, run.trigger, run.schedule_id, run.template_id, run.name) == ("queued", "schedule", schedule.id, template.id, "Daily")
        assert (run.window_start, run.window_end) == (datetime(2026, 10, 13, tzinfo=UTC), datetime(2026, 10, 14, tzinfo=UTC))

        after = ReportScheduleResponse.model_validate((await client.get(url(site_id, f"/schedules/{schedule.id}"))).json())
        assert after.next_run_at == datetime(2026, 10, 15, 6, 0, tzinfo=UTC)
        assert after.last_run_at is not None

        assert await process_queued_runs(BackendOtReportSource()) == 1
        generated = ReportRunResponse.model_validate((await client.get(url(site_id, f"/runs/{run.id}"))).json())
        assert generated.status == "succeeded" and generated.result is not None

    async def test_after_downtime_one_catch_up_then_from_now(self, client, db):
        site_id, template = await site_with_template(client)
        schedule = await create_schedule(client, site_id, template_id=template.id)
        await make_due(db, schedule.id, datetime(2026, 10, 10, 6, 0, tzinfo=UTC))
        now = datetime(2026, 10, 14, 12, 0, tzinfo=UTC)  # four occurrences missed
        assert await dispatch_due_schedules(BackendOtReportSource(), clock=lambda: now) == 1
        assert await dispatch_due_schedules(BackendOtReportSource(), clock=lambda: now) == 0
        assert len(await runs_of(client, site_id)) == 1
        after = ReportScheduleResponse.model_validate((await client.get(url(site_id, f"/schedules/{schedule.id}"))).json())
        assert after.next_run_at == datetime(2026, 10, 15, 6, 0, tzinfo=UTC)

    async def test_disabled_and_not_yet_due_schedules_wait(self, client, db):
        site_id, template = await site_with_template(client)
        await create_schedule(client, site_id, template_id=template.id)  # next time is in the future
        off = await create_schedule(client, site_id, template_id=template.id, enabled=False)
        await make_due(db, off.id, datetime.now(UTC) - timedelta(hours=1))
        assert await dispatch_due_schedules(BackendOtReportSource()) == 0
        assert await runs_of(client, site_id) == []

    async def test_keep_last_prunes_only_the_schedules_own_reports(self, client, db):
        site_id, template = await site_with_template(client)
        schedule = await create_schedule(client, site_id, template_id=template.id, keep_last=2)
        manual = (await client.post(url(site_id, "/runs"), json=ReportRunCreateRequest(template_id=template.id).model_dump(mode="json", exclude_none=True))).json()
        due = datetime(2026, 10, 10, 6, 0, tzinfo=UTC)
        for day in range(4):
            await make_due(db, schedule.id, due + timedelta(days=day))
            assert await dispatch_due_schedules(BackendOtReportSource(), clock=lambda day=day: due + timedelta(days=day, minutes=1)) == 1
        runs = await runs_of(client, site_id)
        scheduled = [run for run in runs if run.schedule_id == schedule.id]
        assert len(scheduled) == 2
        assert sorted(run.window_end for run in scheduled) == [datetime(2026, 10, 12, tzinfo=UTC), datetime(2026, 10, 13, tzinfo=UTC)]
        assert manual["id"] in [run.id for run in runs]  # a report requested by hand is never pruned

    async def test_keep_days_prunes_old_reports(self, client, db):
        site_id, template = await site_with_template(client)
        schedule = await create_schedule(client, site_id, template_id=template.id, keep_days=7)
        await make_due(db, schedule.id, datetime.now(UTC) - timedelta(minutes=1))
        assert await dispatch_due_schedules(BackendOtReportSource()) == 1
        (old,) = await runs_of(client, site_id)
        await db.execute("UPDATE report_runs SET requested_at = now() - interval '8 days' WHERE id = $1", old.id)
        await make_due(db, schedule.id, datetime.now(UTC) - timedelta(minutes=1))
        assert await dispatch_due_schedules(BackendOtReportSource()) == 1
        (kept,) = await runs_of(client, site_id)
        assert kept.id != old.id

    async def test_template_that_no_longer_fits_records_a_failed_report(self, client, db):
        site = await create_site(client)
        device = await create_device(client, site.site_id)
        (power,) = await upsert_points(client, site.site_id, device.device_id, [point_request()])
        definition = ReportDefinition(window=RollingWindow(kind="rolling", duration="1D"), blocks=[TextBlock(kind="text", id="intro", body=f"{{point:{power.id}.max}}")])
        template = ReportTemplateResponse.model_validate((await client.post(url(site.site_id, "/templates"), json=ReportTemplateCreateRequest(name="Power", definition=definition).model_dump(mode="json"))).json())
        schedule = await create_schedule(client, site.site_id, template_id=template.id)
        await db.execute("UPDATE device_points SET deleted_at = now() WHERE id = $1", power.id)  # the point goes away
        await make_due(db, schedule.id, datetime.now(UTC) - timedelta(minutes=1))

        assert await dispatch_due_schedules(BackendOtReportSource()) == 1
        (run,) = await runs_of(client, site.site_id)
        assert run.status == "failed" and run.error is not None
        assert run.error.startswith("The template no longer fits the site: intro:") and "not on this site" in run.error
        assert await process_queued_runs(BackendOtReportSource()) == 0  # nothing left to generate

    async def test_soft_deleted_site_moves_on_without_reports(self, client, db):
        site_id, template = await site_with_template(client)
        schedule = await create_schedule(client, site_id, template_id=template.id)
        await make_due(db, schedule.id, datetime.now(UTC) - timedelta(minutes=1))
        assert (await client.delete(f"/api/sites/{site_id}")).status_code == 200
        await dispatch_due_schedules(BackendOtReportSource())
        assert await db.fetchval("SELECT count(*) FROM report_runs WHERE site_id = $1", site_id) == 0
        assert await db.fetchval("SELECT next_run_at > now() FROM report_schedules WHERE id = $1", schedule.id)

    async def test_runs_list_filters_by_schedule(self, client, db):
        site_id, template = await site_with_template(client)
        schedule = await create_schedule(client, site_id, template_id=template.id)
        await client.post(url(site_id, "/runs"), json=ReportRunCreateRequest(template_id=template.id).model_dump(mode="json", exclude_none=True))
        await make_due(db, schedule.id, datetime.now(UTC) - timedelta(minutes=1))
        await dispatch_due_schedules(BackendOtReportSource())
        response = await client.get(url(site_id, "/runs"), params={"schedule_id": schedule.id})
        assert [run.schedule_id for run in RUN_LIST.validate_python(response.json())] == [schedule.id]
