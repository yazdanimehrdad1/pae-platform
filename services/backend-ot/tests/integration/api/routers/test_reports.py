    async def test_update_bumps_the_version_only_for_a_changed_definition(self, client):
        site_id, _, power, voltage = await site_with_power(client)
        report = definition(ChartBlock(kind="chart", id="chart", series=[PointSeries(source="point", point_id=power.id)]))
        template = await create_template(client, site_id, "Power", report)
        path = reports_url(site_id, f"/templates/{template.id}")

        renamed = await client.put(path, json=ReportTemplateUpdateRequest(name="Power v2", definition=report).model_dump(mode="json", exclude_unset=True))
        assert ReportTemplateResponse.model_validate(renamed.json()).version == 1

        changed = definition(ChartBlock(kind="chart", id="chart", series=[PointSeries(source="point", point_id=voltage.id)]))
        updated = await client.put(path, json=ReportTemplateUpdateRequest(definition=changed).model_dump(mode="json", exclude_unset=True))
        assert updated.status_code == 200, updated.text
        result = ReportTemplateResponse.model_validate(updated.json())
        assert (result.name, result.version, result.definition) == ("Power v2", 2, changed)

