    async def test_list_filters_and_leaves_out_the_data(self, client):
        site_id, _, _, _ = await site_with_power(client)
        template = await create_template(client, site_id, "Intro", definition(TextBlock(kind="text", id="intro", body="x")))
        done = await generated(client, site_id, ReportRunCreateRequest(template_id=template.id))
        queued = await request_run(client, site_id, ReportRunCreateRequest(definition=definition(TextBlock(kind="text", id="other", body="y"))))

        everything = RUN_LIST.validate_python((await client.get(reports_url(site_id, "/runs"))).json())
        assert [run.id for run in everything] == [queued.id, done.id]  # newest first
        only_queued = RUN_LIST.validate_python((await client.get(reports_url(site_id, "/runs"), params={"status": "queued"})).json())
        assert [run.id for run in only_queued] == [queued.id]
        of_template = RUN_LIST.validate_python((await client.get(reports_url(site_id, "/runs"), params={"template_id": template.id})).json())
        assert [run.id for run in of_template] == [done.id]
        assert "result" not in (await client.get(reports_url(site_id, "/runs"))).json()[0]

