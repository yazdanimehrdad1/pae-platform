class TestRuns:
    async def test_requested_run_is_queued_with_its_window_resolved(self, client):
        site_id, _, power, _ = await site_with_power(client)
        before = datetime.now(UTC)
        run = await request_run(client, site_id, ReportRunCreateRequest(
            definition=definition(ChartBlock(kind="chart", id="chart", series=[PointSeries(source="point", point_id=power.id)]), window=RollingWindow(kind="rolling", duration="1D")),
        ))
        assert (run.status, run.result, run.name) == ("queued", None, "Custom report")
        assert run.window_end >= before and run.window_end - run.window_start == timedelta(days=1)

    async def test_from_a_template_with_a_custom_window(self, client):
        site_id, _, _, _ = await site_with_power(client)
        template = await create_template(client, site_id, "Intro", definition(TextBlock(kind="text", id="intro", body="x"), window=RollingWindow(kind="rolling", duration="1D")))
