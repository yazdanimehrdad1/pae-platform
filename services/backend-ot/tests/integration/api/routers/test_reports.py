    async def test_day_buckets_follow_the_site_time_zone(self, client, db):
        site_id, _, power, _ = await site_with_power(client, timezone="America/Los_Angeles")
        # 07:30 and 08:30 UTC on Jan 15 are 23:30 on the 14th and 00:30 on the 15th in Los Angeles (PST)
        await insert_readings(db, power, [(datetime(2026, 1, 15, 7, 30, tzinfo=UTC), 1.0), (datetime(2026, 1, 15, 8, 30, tzinfo=UTC), 3.0)])
        window = FixedWindow(kind="fixed", start_time=datetime(2026, 1, 14, tzinfo=UTC), end_time=datetime(2026, 1, 16, tzinfo=UTC))
        report = definition(PointStatsTableBlock(kind="point_stats_table", id="daily", point_ids=[power.id], stats=["avg"], bucket="day"), window=window)
        run = await generated(client, site_id, ReportRunCreateRequest(definition=report))
        assert run.result is not None and run.result.timezone == "America/Los_Angeles"
        (daily,) = run.result.blocks
        assert isinstance(daily, PointStatsTableResult)
        assert [(row.bucket_start, row.values["avg"]) for row in daily.rows] == [
            (datetime(2026, 1, 14, 8, 0, tzinfo=UTC), 1.0),  # local midnight of the 14th
            (datetime(2026, 1, 15, 8, 0, tzinfo=UTC), 3.0),
        ]

