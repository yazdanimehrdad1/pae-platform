        assert await process_queued_runs(BackendOtReportSource()) == 1
        row = await db.fetchrow("SELECT status, error FROM report_runs WHERE id = $1", run.id)
        assert (row["status"], row["error"]) == ("failed", f"Site {site_id} no longer exists")
