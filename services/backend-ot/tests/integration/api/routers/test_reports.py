        run = await request_run(client, site_id, ReportRunCreateRequest(template_id=template.id, window=custom))
        assert (run.name, run.template_id, run.template_version) == ("Intro", template.id, 1)
        assert (run.window_start, run.window_end, run.definition.window) == (BASE, BASE + timedelta(minutes=30), custom)

