BASE = datetime(2026, 1, 15, 12, 0, tzinfo=UTC)
TWO_HOURS = FixedWindow(kind="fixed", start_time=BASE, end_time=BASE + timedelta(hours=2))
TEMPLATE_LIST = TypeAdapter(list[ReportTemplateResponse])
RUN_LIST = TypeAdapter(list[ReportRunSummary])


def reports_url(site_id: int, path: str = "") -> str:
    return f"/api/reports/site/{site_id}{path}"


def definition(*blocks, window=TWO_HOURS) -> ReportDefinition:
    return ReportDefinition(window=window, blocks=list(blocks))


async def site_with_power(client: AsyncClient, **site_overrides: object) -> tuple[int, int, DevicePointResponse, DevicePointResponse]:
    """A site with one meter that has an active_power (kW) and a voltage point."""
    site = await create_site(client, **site_overrides)
    device = await create_device(client, site.site_id, name="meter_1")
    power, voltage = await upsert_points(client, site.site_id, device.device_id, [
        point_request(name="active_power", unit="kW"),
        point_request(name="voltage", address=102, unit="V"),
    ])
    return site.site_id, device.device_id, power, voltage


async def create_template(client: AsyncClient, site_id: int, name: str, report: ReportDefinition) -> ReportTemplateResponse:
    body = ReportTemplateCreateRequest(name=name, definition=report)
    response = await client.post(reports_url(site_id, "/templates"), json=body.model_dump(mode="json"))
    assert response.status_code == 201, response.text
    return ReportTemplateResponse.model_validate(response.json())


async def request_run(client: AsyncClient, site_id: int, request: ReportRunCreateRequest) -> ReportRunResponse:
    response = await client.post(reports_url(site_id, "/runs"), json=request.model_dump(mode="json", exclude_none=True))
    assert response.status_code == 202, response.text
    return ReportRunResponse.model_validate(response.json())


async def generated(client: AsyncClient, site_id: int, request: ReportRunCreateRequest) -> ReportRunResponse:
    """Request a run, let the worker generate it, and read it back."""
    run = await request_run(client, site_id, request)
    assert await process_queued_runs(BackendOtReportSource()) == 1
    response = await client.get(reports_url(site_id, f"/runs/{run.id}"))
    assert response.status_code == 200, response.text
    return ReportRunResponse.model_validate(response.json())


def validation_errors(response) -> list[str]:
    assert response.status_code == 400, response.text
    return ApiValidationErrorResponse.model_validate(response.json()).detail.errors


