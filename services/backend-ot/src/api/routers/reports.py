# --- Runs --------------------------------------------------------------------------------


@router.post(
    "/site/{site_id}/runs",
    response_model=ReportRunResponse,
    status_code=status.HTTP_202_ACCEPTED,
    summary="Request a report (from a template or an inline definition)",
)
async def request_run(site_id: int, body: ReportRunCreateRequest) -> ReportRunResponse:
    """Queues the report and returns it 'queued'; poll GET .../runs/{run_id} until it is 'succeeded'
    (with `result`) or 'failed' (with `error`). The window is resolved now, in the site's time zone,
    and may be at most 92 days (400). `window` replaces the definition's window for this report only."""
    try:
        return await service.request_run(site_id, body, data_source, datetime.now(UTC))
    except Exception as e:
        _report_error(e)


@router.get(
    "/site/{site_id}/runs",
    response_model=list[ReportRunSummary],
    summary="List a site's reports (without their data)",
)
async def list_runs(
    site_id: int,
    template_id: int | None = Query(None, description="Only the reports of this template"),
    status_filter: ReportRunStatus | None = Query(None, alias="status", description="Only reports in this state"),
    schedule_id: int | None = Query(None, description="Only the reports of this schedule"),
    limit: int = Query(50, ge=1, le=200),
) -> list[ReportRunSummary]:
    """Newest request first."""
    try:
        return await service.list_runs(
            site_id, data_source, template_id=template_id, status=status_filter, limit=limit, schedule_id=schedule_id,
        )
    except Exception as e:
        _report_error(e)


