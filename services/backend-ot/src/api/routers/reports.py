"""Report endpoints: a site's report templates, its runs (queued or generated reports with their
stored results) and the catalog the report builder offers. Reports are generated by the scheduler
job 'report_worker', not in the request: a requested run is 202 and 'queued' until then."""

from datetime import UTC, datetime
from typing import NoReturn

from fastapi import APIRouter, HTTPException, Query, status

from logger import get_logger
from reports import schedule_service, service
from reports.backend_ot_source import BackendOtReportSource
from schemas.reports.api import (
    ReportCatalogResponse,
    ReportRunCreateRequest,
    ReportRunResponse,
    ReportRunsDeleteResponse,
    ReportRunStatus,
    ReportRunSummary,
    ReportScheduleResponse,
    ReportTemplateCreateRequest,
    ReportTemplateResponse,
    ReportTemplateUpdateRequest,
)
from schemas.reports.schedules import ReportScheduleCreateRequest, ReportScheduleUpdateRequest
from utils.exceptions import AppError

router = APIRouter(prefix="/reports", tags=["reports"])
logger = get_logger(__name__)

data_source = BackendOtReportSource()


def _report_error(e: Exception) -> NoReturn:
    """Map an exception to an HTTPException. Never returns."""
    if isinstance(e, AppError):
        detail = {"error": type(e).__name__, "message": e.message}
        if e.payload:
            detail.update(e.payload)
        raise HTTPException(status_code=e.http_status_code, detail=detail) from e
    logger.error(f"Unexpected error: {e}", exc_info=True)
    raise HTTPException(
        status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="An internal server error occurred"
    ) from e


@router.get(
    "/site/{site_id}/catalog",
    response_model=ReportCatalogResponse,
    summary="What a report on this site can contain: block kinds, statistics, site functions",
)
async def get_catalog(site_id: int) -> ReportCatalogResponse:
    """The site's time zone (local days and buckets), the block kinds and point statistics, and the
    site functions its profile offers: series ones for charts, numeric fields for KPIs."""
    try:
        return await service.get_catalog(site_id, data_source)
    except Exception as e:
        _report_error(e)


